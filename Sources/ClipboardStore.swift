import AppKit
import Combine

/// Watches the clipboard, keeps the history and saves it to disk.
final class ClipboardStore: ObservableObject {
    @Published private(set) var items: [ClipItem] = []
    @Published var isPaused: Bool {
        didSet { UserDefaults.standard.set(isPaused, forKey: "paused") }
    }
    @Published private(set) var totalCopies: Int

    /// Called whenever a brand-new copy lands in the pot.
    var onNewClip: (() -> Void)?

    let fileURL: URL
    private var lastChangeCount: Int
    private var timer: Timer?
    private var saveWork: DispatchWorkItem?

    /// Clipboard types that password managers and other apps use to say "don't record me".
    private let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "com.typeit4me.clipping",
    ]

    /// Choices for "Keep up to". `-1` means unlimited.
    static let historyLimitOptions = [5, 25, 100, -1]
    static let unlimited = -1

    var historyLimit: Int {
        let v = UserDefaults.standard.integer(forKey: "historyLimit")
        return ClipboardStore.historyLimitOptions.contains(v) ? v : ClipboardStore.unlimited
    }

    init() {
        let fm = FileManager.default
        let support = fm.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
        let dir = support.appendingPathComponent("Pasta", isDirectory: true)
        try? fm.createDirectory(at: dir, withIntermediateDirectories: true)
        fileURL = dir.appendingPathComponent("history.json")

        // Older versions offered 100–5000 (default 500). Anything not in the new list
        // becomes Unlimited, so no one loses history by updating.
        let savedLimit = UserDefaults.standard.integer(forKey: "historyLimit")
        if !ClipboardStore.historyLimitOptions.contains(savedLimit) {
            UserDefaults.standard.set(ClipboardStore.unlimited, forKey: "historyLimit")
        }

        isPaused = UserDefaults.standard.bool(forKey: "paused")
        totalCopies = UserDefaults.standard.integer(forKey: "totalCopies")
        lastChangeCount = NSPasteboard.general.changeCount
        load()
    }

    // MARK: Watching

    func start() {
        let t = Timer(timeInterval: 0.4, repeats: true) { [weak self] _ in
            self?.poll()
        }
        t.tolerance = 0.1
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChangeCount else { return }
        lastChangeCount = pb.changeCount
        guard !isPaused else { return }

        let types = pb.types ?? []
        if types.contains(where: { privateTypes.contains($0.rawValue) }) { return }

        guard let s = pb.string(forType: .string),
              !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
              s.utf8.count <= 2_000_000 else { return }

        let front = NSWorkspace.shared.frontmostApplication
        add(text: s, appName: front?.localizedName, bundleID: front?.bundleIdentifier)
        onNewClip?()
    }

    // MARK: Editing

    @discardableResult
    func add(text: String, appName: String?, bundleID: String?) -> ClipItem {
        totalCopies += 1
        UserDefaults.standard.set(totalCopies, forKey: "totalCopies")

        let result: ClipItem
        if let idx = items.firstIndex(where: { $0.text == text }) {
            var item = items.remove(at: idx)
            item.date = Date()
            item.copyCount += 1
            if appName != nil {
                item.appName = appName
                item.bundleID = bundleID
            }
            items.insert(item, at: 0)
            result = item
        } else {
            let item = ClipItem(text: text, appName: appName, bundleID: bundleID)
            items.insert(item, at: 0)
            trim()
            result = item
        }
        scheduleSave()
        return result
    }

    /// Puts an item back on the clipboard and bumps it to the top.
    func copy(_ item: ClipItem) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(item.text, forType: .string)
        lastChangeCount = pb.changeCount   // don't record our own write

        if let idx = items.firstIndex(where: { $0.id == item.id }) {
            var it = items.remove(at: idx)
            it.date = Date()
            it.copyCount += 1
            items.insert(it, at: 0)
            scheduleSave()
        }
    }

    func togglePin(_ item: ClipItem) {
        guard let idx = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[idx].pinned.toggle()
        scheduleSave()
    }

    func delete(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
        scheduleSave()
    }

    /// Clears everything except pinned items.
    func clearAll() {
        items = items.filter { $0.pinned }
        scheduleSave()
    }

    func applyLimit() {
        trim()
        scheduleSave()
    }

    private func trim() {
        let limit = historyLimit
        guard limit > 0 else { return }   // unlimited
        var unpinned = 0
        let trimmed = items.filter { item in
            if item.pinned { return true }
            unpinned += 1
            return unpinned <= limit
        }
        if trimmed.count != items.count { items = trimmed }
    }

    // MARK: Search

    func search(_ query: String, filter: ClipFilter, sort: ClipSort) -> [ClipItem] {
        let terms = query.split(whereSeparator: { $0.isWhitespace }).map(String.init)

        var result = items.filter { item in
            switch filter {
            case .all: return true
            case .pinned: return item.pinned
            case .kind(let k): return item.kind == k
            }
        }
        if !terms.isEmpty {
            result = result.filter { item in terms.allSatisfy { matches(item, $0) } }
        }
        switch sort {
        case .lastUsed: result.sort { $0.date > $1.date }
        case .created: result.sort { $0.createdAt > $1.createdAt }
        }
        if filter == .all {
            // Pinned favourites float to the top.
            result = result.filter { $0.pinned } + result.filter { !$0.pinned }
        }
        return result
    }

    private func matches(_ item: ClipItem, _ term: String) -> Bool {
        let opts: String.CompareOptions = [.caseInsensitive, .diacriticInsensitive]
        if item.text.range(of: term, options: opts) != nil { return true }
        if let app = item.appName, app.range(of: term, options: opts) != nil { return true }
        if item.kind.pastaName.range(of: term, options: opts) != nil { return true }
        return false
    }

    var pinnedCount: Int { items.filter { $0.pinned }.count }

    var kindCounts: [KindCount] {
        var counts: [ClipKind: Int] = [:]
        for i in items { counts[i.kind, default: 0] += 1 }
        return ClipKind.allCases.compactMap { k in
            guard let c = counts[k] else { return nil }
            return KindCount(kind: k, count: c)
        }
    }

    // MARK: Persistence

    private func load() {
        guard let data = try? Data(contentsOf: fileURL),
              let decoded = try? JSONDecoder().decode([ClipItem].self, from: data) else { return }
        items = decoded
    }

    private func scheduleSave() {
        saveWork?.cancel()
        let snapshot = items
        let url = fileURL
        let work = DispatchWorkItem {
            ClipboardStore.write(snapshot, to: url)
        }
        saveWork = work
        DispatchQueue.global(qos: .utility).asyncAfter(deadline: .now() + 0.6, execute: work)
    }

    func saveNow() {
        saveWork?.cancel()
        ClipboardStore.write(items, to: fileURL)
    }

    private static func write(_ items: [ClipItem], to url: URL) {
        guard let data = try? JSONEncoder().encode(items) else { return }
        try? data.write(to: url, options: .atomic)
        try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
    }
}
